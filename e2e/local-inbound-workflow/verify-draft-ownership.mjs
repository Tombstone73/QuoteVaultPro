import { chromium, expect } from '@playwright/test';
import { startFixture } from './server.mjs';
import { mkdir } from 'node:fs/promises';
const server = await startFixture();
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  await mkdir('node_modules/.cache/inbound-workflow', { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  page.setDefaultTimeout(60000);
  page.on('dialog', dialog => dialog.accept());
  await page.goto('http://127.0.0.1:4187/inbound-orders', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.getByRole('button', { name: 'Inspect ZIP in app' }).click();
  await page.getByRole('button', { name: 'Import selected files together' }).click();
  await expect(page.getByTestId('inbound-archive-resolution')).toContainText('Imported 2 file(s)');
  await page.getByText('I reviewed the entire archive and selected all extracted files needed for this order', { exact: false }).click();
  await page.getByRole('button', { name: 'Confirm reviewed archive evidence' }).click();
  await page.getByRole('button', { name: 'Parse', exact: true }).click();
  const workstation = page.getByTestId('clean-order-workstation');
  const quantity = page.getByTestId('clean-inline-quantity-input');
  await expect(quantity).toHaveValue('20');
  await page.getByRole('combobox', { name: 'Change product' }).click();
  await page.getByText('Coroplast Custom', { exact: true }).last().click();
  const width = workstation.getByLabel('Width', { exact: true });
  const height = workstation.getByLabel('Height', { exact: true });
  await width.fill('24'); await height.fill('18'); await quantity.fill('28');
  await page.getByTestId('order-line-pricing-row').getByRole('button', { name: '$165.00', exact: true }).click();
  await page.getByTestId('order-line-pricing-row').getByRole('textbox').last().fill('165.00');
  await page.getByTestId('order-line-pricing-row').getByRole('textbox').last().blur();
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect(workstation.getByRole('alert')).toContainText('Synthetic first draft save failure');
  await expect(quantity).toHaveValue('28'); await expect(width).toHaveValue('24');
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect.poll(async () => (await page.evaluate(() => window.__fixtureState())).savedReviewDraft?.reviewedLineItemsJson[0].quantity).toBe(28);
  const saved = await page.evaluate(() => window.__fixtureState().savedReviewDraft.reviewedLineItemsJson[0]);
  if (saved.pricingReviewJson.priceOverrideValueCents !== 16500 || saved.width !== 24 || saved.height !== 18) throw new Error('Fixture save did not retain edited size and exact total');
  await quantity.fill('31');
  await page.evaluate(() => window.__fixtureBackgroundRefresh());
  await expect(workstation).toContainText('Saved draft changed');
  await page.waitForTimeout(4000); // exceed the reported delayed-reset window
  await expect(quantity).toHaveValue('31'); await expect(width).toHaveValue('24'); await expect(height).toHaveValue('18');
  await page.getByTestId('clean-readiness-status-bar').getByRole('button', { name: 'Next Issue' }).click();
  await expect(quantity).toHaveValue('31');
  await page.screenshot({ path: 'node_modules/.cache/inbound-workflow/dirty-background-preserved.png' });
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect(workstation).toContainText('Draft was not saved or refreshed: Saved draft changed');
  await expect(quantity).toHaveValue('31');
  await page.getByRole('button', { name: 'Refresh from Latest Parse', exact: true }).click();
  await expect(workstation).toContainText('Draft was not saved or refreshed: Saved draft changed');
  await expect(quantity).toHaveValue('31');
  await page.getByRole('button', { name: 'Load current saved draft', exact: true }).click();
  await expect(quantity).toHaveValue('28');
  await page.getByRole('button', { name: 'Refresh from Latest Parse', exact: true }).click();
  await expect(quantity).toHaveValue('28');
  await expect(workstation).toContainText('Coroplast Custom');
  console.log('DRAFT OWNERSHIP: dirty background refetch, failed save, exact override, stale conflict, Next Issue, explicit reload/reconciliation passed; browser persistence is mocked.');
} finally { await browser.close(); await server.close(); }
