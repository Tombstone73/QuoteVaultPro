import { chromium, expect } from '@playwright/test';
import { startFixture } from './server.mjs';
import { mkdir } from 'node:fs/promises';
const server = await startFixture();
const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  await mkdir('node_modules/.cache/inbound-workflow', { recursive: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  page.setDefaultTimeout(60000);
  page.on('dialog', dialog => dialog.accept());
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:4187/inbound-orders', { waitUntil: 'domcontentloaded', timeout: 60000 });
  await page.getByRole('button', { name: 'Inspect ZIP in app' }).click();
  await page.getByRole('button', { name: 'Import selected files together' }).click();
  await expect(page.getByTestId('inbound-archive-resolution')).toContainText('Imported 2 file(s)');
  await page.getByText('I reviewed the entire archive and selected all extracted files needed for this order', { exact: false }).click();
  await page.getByRole('button', { name: 'Confirm reviewed archive evidence' }).click();
  await page.getByRole('button', { name: 'Parse', exact: true }).click();
  await expect(page.getByTestId('clean-inline-quantity-input')).toHaveValue('20');
  await page.evaluate(() => window.__fixtureEditorRepair());
  const workstation = page.getByTestId('clean-order-workstation');
  const readiness = page.getByTestId('clean-readiness-status-bar');
  await expect(readiness).toContainText('AI reported missing product');
  // Bring the automatically opened picker into view before pointer selection.
  await page.keyboard.press('Escape');
  await page.getByRole('combobox', { name: 'Select product' }).scrollIntoViewIfNeeded();
  await page.getByRole('combobox', { name: 'Select product' }).press('Enter');
  await expect(page.getByRole('option', { name: /Coroplast Custom/ })).toBeVisible();
  await page.getByPlaceholder('Search by name, SKU, or category…').press('ArrowDown');
  await page.getByPlaceholder('Search by name, SKU, or category…').press('Enter');
  await expect(readiness).not.toContainText('AI reported missing product');
  await expect(page.getByRole('combobox', { name: 'Change product' })).toContainText('Coroplast Custom');
  console.log('Selected current catalog product using keyboard controls.');
  const width = workstation.getByLabel('Width', { exact: true });
  const height = workstation.getByLabel('Height', { exact: true });
  await width.fill('2'); await width.press('End'); await width.pressSequentially('.25');
  await expect(width).toHaveValue('2.25'); await width.blur();
  for (const value of ['0.5', '12.75', '2']) { await height.fill(value); await height.blur(); await expect(height).toHaveValue(value); }
  await width.fill('2'); await width.blur();
  const quantity = page.getByTestId('clean-inline-quantity-input'); await quantity.fill('125'); await quantity.blur();
  await expect(readiness).not.toContainText('AI reported missing dimensions');
  await expect(readiness).not.toContainText('AI reported missing quantity');
  await page.getByTestId('clean-inline-artwork-select').selectOption({ label: 'front.pdf' });
  await expect(readiness).not.toContainText('AI reported missing artwork');
  await expect(page.getByTestId('detected-pdf-line-item-size')).toContainText('2.25 × 2');
  await expect(page.getByTestId('detected-pdf-line-item-size')).toContainText('finished size');
  await expect.poll(async () => (await page.evaluate(() => window.__fixtureState())).lastInboundPricingInput?.width).toBe(2);
  await expect(readiness).toHaveAttribute('data-unresolved-count', '0');
  await expect(readiness.getByRole('button', { name: 'Next Issue' })).toBeDisabled();
  await expect(workstation).toContainText('Historical parse observation');
  for (const theme of ['Light', 'Dark']) {
    await page.getByRole('button', { name: theme, exact: true }).click();
    await page.getByTestId('detected-pdf-line-item-size').scrollIntoViewIfNeeded();
    await page.evaluate(() => window.getSelection()?.removeAllRanges());
    await page.screenshot({ path: `node_modules/.cache/inbound-workflow/editor-repair-${theme.toLowerCase()}.png` });
  }
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect(workstation.getByRole('alert')).toContainText('Synthetic first draft save failure');
  await expect(width).toHaveValue('2'); await expect(quantity).toHaveValue('125');
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect.poll(async () => (await page.evaluate(() => window.__fixtureState())).savedReviewDraft.reviewedLineItemsJson[0].quantity).toBe(125);
  await width.fill('2.');
  await page.evaluate(() => window.__fixtureBackgroundRefresh());
  await page.waitForTimeout(4000);
  await expect(width).toHaveValue('2.'); await expect(quantity).toHaveValue('125');
  await expect(readiness).not.toContainText('AI reported missing product');
  await expect(readiness).not.toContainText('AI reported missing quantity');
  await width.press('End'); await width.pressSequentially('25'); await width.blur();
  await page.getByRole('button', { name: 'Save Draft', exact: true }).click();
  await expect(workstation).toContainText('Draft was not saved or refreshed: Saved draft changed');
  await expect(width).toHaveValue('2.25');
  await page.getByRole('button', { name: 'Load current saved draft', exact: true }).click();
  await expect(width).toHaveValue('2'); await expect(quantity).toHaveValue('125');
  await expect(readiness).not.toContainText('AI reported missing dimensions');
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('EDITOR REPAIR: decimals, selected product, current readiness, artwork/PDF warning, pricing request, Next Issue, failed save, partial input during background refresh, stale-save rejection and explicit saved-draft readback passed. Light/dark screenshots at normal zoom. Browser persistence is mocked; real persistence is covered separately in PostgreSQL.');
} catch (error) {
  const page = browser.contexts()[0]?.pages()[0];
  if (page) await page.screenshot({ path: 'node_modules/.cache/inbound-workflow/editor-repair-failure.png' });
  throw error;
} finally { await browser.close(); await server.close(); }
