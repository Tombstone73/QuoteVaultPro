import { chromium, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

await mkdir('node_modules/.cache/inbound-workflow', { recursive: true });

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
await page.goto('http://127.0.0.1:4187/inbound-orders', { waitUntil: 'networkidle' });
await expect(page.getByTestId('inbound-archive-resolution')).toBeVisible();
await page.getByRole('button', { name: 'Inspect ZIP in app' }).click();
await expect(page.getByTestId('inbound-zip-manifest')).toContainText('2 eligible file(s)');
await expect(page.getByTestId('inbound-zip-manifest')).toContainText('script.exe');
await page.getByRole('button', { name: 'Import selected files together' }).click();
await expect(page.getByTestId('inbound-archive-resolution')).toContainText('Imported 2 file(s)');
await page.getByText('I reviewed the entire archive and selected all extracted files needed for this order', { exact: false }).click();
await page.getByRole('button', { name: 'Confirm reviewed archive evidence' }).click();
await expect(page.getByTestId('inbound-archive-resolution')).toContainText('Archive evidence reviewed');
await page.getByRole('button', { name: 'Parse', exact: true }).click();
await expect(page.getByTestId('clean-order-workstation')).toBeVisible();
await expect(page.getByTestId('order-entry-workspace')).toBeVisible();
await expect(page.getByTestId('inbound-fixed-product-size').first()).toContainText('24 × 18');
await expect(page.getByTestId('clean-order-workstation')).toContainText('Yard Signs 24x18');
await expect(page.getByTestId('clean-order-workstation')).toContainText('Qty 20');
await expect(page.getByTestId('clean-order-workstation')).toContainText('double-sided');
await page.getByText('Send to Prepress', { exact: true }).click();
await expect(page.getByRole('radio', { name: 'Send to Prepress' })).toBeChecked();
await page.getByRole('button', { name: 'Dark', exact: true }).click();
await page.screenshot({ path: 'node_modules/.cache/inbound-workflow/dark.png', fullPage: true });
await expect(page.locator('html')).toHaveClass(/dark/);
await page.getByRole('button', { name: 'Light', exact: true }).click();
await page.screenshot({ path: 'node_modules/.cache/inbound-workflow/light.png', fullPage: true });
await expect(page.locator('html')).not.toHaveClass(/dark/);
await page.getByRole('button', { name: 'Create Order' }).click();
await expect(page.locator('body')).toContainText('Draft order created');
const state = await page.evaluate(() => (window).__fixtureState());
console.log('BROWSER JOURNEY', state);
console.log('ERRORS', errors);
if (errors.length) process.exitCode = 1;
await browser.close();
